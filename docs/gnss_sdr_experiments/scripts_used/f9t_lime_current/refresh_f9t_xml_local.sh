#!/usr/bin/env bash
set -euo pipefail

DURATION="${1:-600}"          # default 10 min
MIN_BYTES="${2:-50000}"       # minimum capture size before converting

PORT="${F9T_PORT:-/dev/ttyUSB0}"
BAUD="${F9T_BAUD:-38400}"

BASE="$HOME/gnss/f9t"
RAW_DIR="$BASE/local"
RINEX_DIR="$BASE/rinex"
ASSIST_RUNS="$BASE/assist_runs"
LOG_DIR="$BASE/logs"
LATEST_DIR="$HOME/gnss/assist/f9t_tcp_latest"
BACKUP_ROOT="$HOME/gnss/assist/backups"

RINEX2ASSIST="$HOME/src/gnss-sdr-0.0.16/build/src/utils/rinex2assist/rinex2assist"

RUN_ID="$(date -u +%Y%m%d_%H%M%S)"
LOCK="$BASE/refresh_f9t_xml_local.lock"

mkdir -p "$RAW_DIR" "$RINEX_DIR" "$ASSIST_RUNS" "$LOG_DIR" "$LATEST_DIR" "$BACKUP_ROOT"

exec 9>"$LOCK"
if ! flock -n 9; then
  echo "ERROR: another local F9T refresh is already running."
  exit 1
fi

RAW="$RAW_DIR/hft02_${PORT##*/}_${RUN_ID}_${DURATION}s.ubx"
OBS="$RINEX_DIR/hft02_${PORT##*/}_${RUN_ID}.obs"
NAV="$RINEX_DIR/hft02_${PORT##*/}_${RUN_ID}.nav"
ASSIST_DIR="$ASSIST_RUNS/hft02_${RUN_ID}"
LOG="$LOG_DIR/refresh_local_${RUN_ID}.log"

{
  echo "======================================================"
  echo "Local F9T XML refresh run"
  echo "RUN_ID: $RUN_ID"
  echo "UTC start: $(date -u)"
  echo "Duration: ${DURATION}s"
  echo "Serial port: $PORT"
  echo "Baud: $BAUD"
  echo "Output RAW: $RAW"
  echo "======================================================"
} | tee "$LOG"

command -v convbin >/dev/null || { echo "ERROR: convbin not found" | tee -a "$LOG"; exit 1; }
[ -x "$RINEX2ASSIST" ] || { echo "ERROR: rinex2assist not found at $RINEX2ASSIST" | tee -a "$LOG"; exit 1; }
[ -e "$PORT" ] || { echo "ERROR: serial port $PORT does not exist" | tee -a "$LOG"; exit 1; }

echo "" | tee -a "$LOG"
echo "=== 1. Capturing local F9T serial stream ===" | tee -a "$LOG"

stty -F "$PORT" raw -echo "$BAUD" 2>/dev/null || true

timeout "${DURATION}s" cat "$PORT" > "$RAW" &
CAP_PID=$!

while kill -0 "$CAP_PID" 2>/dev/null; do
  BYTES_NOW=$(stat -c%s "$RAW" 2>/dev/null || echo 0)
  echo "$(date -u '+%H:%M:%S UTC') captured ${BYTES_NOW} bytes" | tee -a "$LOG"
  sleep 10
done

wait "$CAP_PID" || true

BYTES=$(stat -c%s "$RAW" 2>/dev/null || echo 0)

{
  echo ""
  echo "UTC capture end: $(date -u)"
  echo "Bytes captured: $BYTES"
  ls -lh "$RAW"
} | tee -a "$LOG"

if [ "$BYTES" -lt "$MIN_BYTES" ]; then
  echo "ERROR: capture too small. Not updating XML." | tee -a "$LOG"
  exit 1
fi

echo "" | tee -a "$LOG"
echo "=== 2. Quick stream inspection ===" | tee -a "$LOG"

python3 - "$RAW" <<'PY' | tee -a "$LOG"
from pathlib import Path
import sys
data = Path(sys.argv[1]).read_bytes()
print("bytes:", len(data))
print("NMEA count:", data.count(b"$GN") + data.count(b"$GP"))
print("UBX sync count:", data.count(b"\xb5\x62"))
print("RTCM3 sync-ish count:", data.count(b"\xd3"))
PY

echo "" | tee -a "$LOG"
echo "=== 3. Converting UBX to RINEX NAV/OBS ===" | tee -a "$LOG"

convbin -r ubx -v 3.04 \
  -o "$OBS" \
  -n "$NAV" \
  "$RAW" 2>&1 | tee -a "$LOG"

echo "" | tee -a "$LOG"
echo "RINEX outputs:" | tee -a "$LOG"
ls -lh "$OBS" "$NAV" 2>/dev/null | tee -a "$LOG" || true

if [ ! -s "$NAV" ]; then
  echo "ERROR: RINEX NAV file missing or empty. Not updating XML." | tee -a "$LOG"
  exit 1
fi

GPS_LIST="$(grep -E '^G[0-9]{2} ' "$NAV" 2>/dev/null | awk '{print $1}' | sort -u || true)"
GPS_COUNT="$(printf "%s\n" "$GPS_LIST" | grep -c '^G' || true)"

{
  echo ""
  echo "=== 4. GPS ephemeris satellites in NAV ==="
  echo "$GPS_LIST"
  echo "GPS_COUNT=$GPS_COUNT"
} | tee -a "$LOG"

if [ "$GPS_COUNT" -eq 0 ]; then
  echo "ERROR: no GPS ephemeris found. Not updating XML." | tee -a "$LOG"
  exit 1
fi

echo "" | tee -a "$LOG"
echo "=== 5. Running rinex2assist ===" | tee -a "$LOG"

mkdir -p "$ASSIST_DIR"
cd "$ASSIST_DIR"

"$RINEX2ASSIST" "$NAV" 2>&1 | tee -a "$LOG"

if [ ! -s "$ASSIST_DIR/gps_ephemeris.xml" ]; then
  echo "ERROR: gps_ephemeris.xml was not generated. Not updating latest XML." | tee -a "$LOG"
  exit 1
fi

XML_COUNT="$(grep -o '<count>[0-9]*</count>' "$ASSIST_DIR/gps_ephemeris.xml" || true)"

{
  echo ""
  echo "Generated XML:"
  ls -lh "$ASSIST_DIR"
  echo "XML count: $XML_COUNT"
} | tee -a "$LOG"

echo "" | tee -a "$LOG"
echo "=== 6. Updating latest XML folder ===" | tee -a "$LOG"

BACKUP_DIR="$BACKUP_ROOT/f9t_tcp_latest_backup_${RUN_ID}"
mkdir -p "$BACKUP_DIR"
cp "$LATEST_DIR"/*.xml "$BACKUP_DIR"/ 2>/dev/null || true

rm -f "$LATEST_DIR"/*.xml
cp "$ASSIST_DIR"/*.xml "$LATEST_DIR"/

cat > "$LATEST_DIR/README_CURRENT_XML.txt" <<TXT
Generated by refresh_f9t_xml_local.sh

RUN_ID: $RUN_ID
UTC generated: $(date -u)
Capture duration: ${DURATION}s
Source: local F9T serial port $PORT
Baud: $BAUD
Raw capture: $RAW
RINEX NAV: $NAV
Assist source dir: $ASSIST_DIR

GPS satellites:
$GPS_LIST

GPS_COUNT: $GPS_COUNT
XML count: $XML_COUNT
TXT

{
  echo ""
  echo "Latest XML folder:"
  ls -lh "$LATEST_DIR"
  echo ""
  echo "DONE"
  echo "RUN_ID=$RUN_ID"
  echo "GPS_COUNT=$GPS_COUNT"
  echo "XML=$LATEST_DIR/gps_ephemeris.xml"
  echo "LOG=$LOG"
} | tee -a "$LOG"
