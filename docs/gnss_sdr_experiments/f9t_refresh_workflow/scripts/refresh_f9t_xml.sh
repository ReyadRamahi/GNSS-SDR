#!/usr/bin/env bash
set -euo pipefail

DURATION="${1:-1800}"          # default 30 min
MIN_BYTES="${2:-50000}"        # minimum capture size before converting

HOST="10.30.200.59"
PORT="50012"

BASE="$HOME/gnss/f9t"
TCP_DIR="$BASE/tcp"
RINEX_DIR="$BASE/rinex"
ASSIST_RUNS="$BASE/assist_runs"
LOG_DIR="$BASE/logs"
LATEST_DIR="$HOME/gnss/assist/f9t_tcp_latest"
BACKUP_ROOT="$HOME/gnss/assist/backups"

RINEX2ASSIST="$HOME/src/gnss-sdr-0.0.16/build/src/utils/rinex2assist/rinex2assist"

RUN_ID="$(date -u +%Y%m%d_%H%M%S)"
LOCK="$BASE/refresh_f9t_xml.lock"

mkdir -p "$TCP_DIR" "$RINEX_DIR" "$ASSIST_RUNS" "$LOG_DIR" "$LATEST_DIR" "$BACKUP_ROOT"

exec 9>"$LOCK"
if ! flock -n 9; then
  echo "ERROR: another refresh_f9t_xml.sh is already running."
  exit 1
fi

BIN="$TCP_DIR/hft09_tcp_${RUN_ID}_${DURATION}s.bin"
OBS="$RINEX_DIR/hft09_tcp_${RUN_ID}.obs"
NAV="$RINEX_DIR/hft09_tcp_${RUN_ID}.nav"
ASSIST_DIR="$ASSIST_RUNS/$RUN_ID"
LOG="$LOG_DIR/refresh_${RUN_ID}.log"

{
  echo "======================================================"
  echo "F9T XML refresh run"
  echo "RUN_ID: $RUN_ID"
  echo "UTC start: $(date -u)"
  echo "Duration: ${DURATION}s"
  echo "Minimum bytes: $MIN_BYTES"
  echo "Source: raw TCP ${HOST}:${PORT}"
  echo "Output BIN: $BIN"
  echo "======================================================"
} | tee "$LOG"

command -v nc >/dev/null || { echo "ERROR: nc not found" | tee -a "$LOG"; exit 1; }
command -v convbin >/dev/null || { echo "ERROR: convbin not found" | tee -a "$LOG"; exit 1; }
[ -x "$RINEX2ASSIST" ] || { echo "ERROR: rinex2assist not found at $RINEX2ASSIST" | tee -a "$LOG"; exit 1; }

echo "" | tee -a "$LOG"
echo "=== 1. Capturing raw TCP stream with nc ===" | tee -a "$LOG"

timeout "${DURATION}s" nc "$HOST" "$PORT" > "$BIN" &
CAP_PID=$!

while kill -0 "$CAP_PID" 2>/dev/null; do
  BYTES_NOW=$(stat -c%s "$BIN" 2>/dev/null || echo 0)
  echo "$(date -u '+%H:%M:%S UTC') captured ${BYTES_NOW} bytes" | tee -a "$LOG"
  sleep 15
done

wait "$CAP_PID" || true

BYTES=$(stat -c%s "$BIN" 2>/dev/null || echo 0)

{
  echo ""
  echo "UTC capture end: $(date -u)"
  echo "Bytes captured: $BYTES"
  ls -lh "$BIN"
} | tee -a "$LOG"

if [ "$BYTES" -lt "$MIN_BYTES" ]; then
  echo "ERROR: capture too small. Stream was weak/stalled. Not updating XML." | tee -a "$LOG"
  exit 1
fi

echo "" | tee -a "$LOG"
echo "=== 2. Converting UBX to RINEX NAV/OBS ===" | tee -a "$LOG"

convbin -r ubx -v 3.04 \
  -o "$OBS" \
  -n "$NAV" \
  "$BIN" 2>&1 | tee -a "$LOG"

echo "" | tee -a "$LOG"
echo "RINEX outputs:" | tee -a "$LOG"
ls -lh "$OBS" "$NAV" 2>/dev/null | tee -a "$LOG" || true

if [ ! -s "$NAV" ]; then
  echo "ERROR: RINEX NAV file missing or empty. Not updating XML." | tee -a "$LOG"
  exit 1
fi

GPS_LIST="$(grep -E '^G[0-9]{2} ' "$NAV" 2>/dev/null | awk '{print $1}' | sort -u || true)"
GPS_COUNT="$(printf "%s\n" "$GPS_LIST" | grep -c '^G' || true)"

{
  echo ""
  echo "=== 3. GPS ephemeris satellites in NAV ==="
  echo "$GPS_LIST"
  echo "GPS_COUNT=$GPS_COUNT"
} | tee -a "$LOG"

if [ "$GPS_COUNT" -eq 0 ]; then
  echo "ERROR: no GPS ephemeris found. Not updating XML." | tee -a "$LOG"
  exit 1
fi

echo "" | tee -a "$LOG"
echo "=== 4. Running rinex2assist ===" | tee -a "$LOG"

mkdir -p "$ASSIST_DIR"
cd "$ASSIST_DIR"

"$RINEX2ASSIST" "$NAV" 2>&1 | tee -a "$LOG"

if [ ! -s "$ASSIST_DIR/gps_ephemeris.xml" ]; then
  echo "ERROR: gps_ephemeris.xml was not generated. Not updating latest XML." | tee -a "$LOG"
  exit 1
fi

XML_COUNT="$(grep -o '<count>[0-9]*</count>' "$ASSIST_DIR/gps_ephemeris.xml" || true)"

{
  echo ""
  echo "Generated XML:"
  ls -lh "$ASSIST_DIR"
  echo "XML count: $XML_COUNT"
} | tee -a "$LOG"

echo "" | tee -a "$LOG"
echo "=== 5. Updating latest XML folder ===" | tee -a "$LOG"

BACKUP_DIR="$BACKUP_ROOT/f9t_tcp_latest_backup_${RUN_ID}"
mkdir -p "$BACKUP_DIR"
cp "$LATEST_DIR"/*.xml "$BACKUP_DIR"/ 2>/dev/null || true

rm -f "$LATEST_DIR"/*.xml
cp "$ASSIST_DIR"/*.xml "$LATEST_DIR"/

cat > "$LATEST_DIR/README_CURRENT_XML.txt" <<TXT
Generated by refresh_f9t_xml.sh

RUN_ID: $RUN_ID
UTC generated: $(date -u)
Capture duration: ${DURATION}s
Source: raw TCP ${HOST}:${PORT}
UBX capture: $BIN
RINEX NAV: $NAV
Assist source dir: $ASSIST_DIR

GPS satellites:
$GPS_LIST

GPS_COUNT: $GPS_COUNT
XML count: $XML_COUNT
TXT

{
  echo ""
  echo "Latest XML folder:"
  ls -lh "$LATEST_DIR"
  echo ""
  echo "DONE"
  echo "RUN_ID=$RUN_ID"
  echo "GPS_COUNT=$GPS_COUNT"
  echo "XML=$LATEST_DIR/gps_ephemeris.xml"
  echo "LOG=$LOG"
} | tee -a "$LOG"
